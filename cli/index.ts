program
  .command("update")
  .description("Update the platform (git pull + rebuild) where this is a git checkout")
  .action(() => {
    const platformRoot = getPlatformRoot();
    const isGitRepo = fs.existsSync(path.join(platformRoot, ".git"));
    if (!isGitRepo) {
      console.log(chalk.yellow(`${platformRoot} is not a git checkout -- nothing to pull. If you installed via npm, use: npm install -g security-platform@latest`));
      return;
    }
    console.log(chalk.bold("Pulling latest changes..."));
    const pull = spawnSync("git", ["-C", platformRoot, "pull", "--ff-only"], { stdio: "inherit", shell: process.platform === "win32" });
    if (pull.status !== 0) {
      console.log(chalk.red("git pull failed. Resolve manually (check for local changes) and re-run."));
      process.exitCode = 1;
      return;
    }
    console.log(chalk.bold("\nRebuilding..."));
    const install = spawnSync("npm", ["install"], { cwd: platformRoot, stdio: "inherit", shell: process.platform === "win32" });
    const build = install.status === 0 ? spawnSync("npm", ["run", "build"], { cwd: platformRoot, stdio: "inherit", shell: process.platform === "win32" }) : install;
    if (build.status !== 0) {
      console.log(chalk.red("Update failed during install/build. See output above."));
      process.exitCode = 1;
      return;
    }
    console.log(chalk.green("\nUpdate complete."));
  });

program
  .command("repair")
  .description("Repair recoverable platform state (missing directories/config)")
  .action(() => {
    const platformRoot = getPlatformRoot();
    console.log(chalk.bold(`Repairing platform at: ${platformRoot}`));
    let repaired = 0;
    for (const dir of ensurePlatformDirectories(platformRoot)) {
      if (dir.created) {
        console.log(chalk.green(`[SUCCESS] Recreated missing directory: ${dir.dirPath}`));
        repaired++;
      }
    }
    const runtimeConfig = ensureRuntimeConfig(platformRoot);
    if (runtimeConfig.created) {
      console.log(chalk.green(`[SUCCESS] Recreated missing runtime config: ${runtimeConfig.path}`));
      repaired++;
    }
    const composePath = path.join(platformRoot, "docker", "docker-compose.yml");
    if (!fs.existsSync(composePath)) {
      console.log(chalk.red(`[ERROR] docker/docker-compose.yml is missing -- this cannot be auto-repaired; re-clone or restore it.`));
      process.exitCode = 1;
    } else {
      const check = spawnSync("docker", ["compose", "-f", composePath, "config"], { encoding: "utf8", shell: process.platform === "win32" });
      if (check.status === 0) {
        console.log(chalk.green("[OK]      docker-compose.yml is valid."));
      } else {
        console.log(chalk.yellow(`[WARNING] docker-compose.yml did not validate (is docker/.env missing ZAP_API_KEY?): ${check.stderr?.trim()}`));
      }
    }
    console.log(repaired > 0 ? chalk.bold(`\nRepair complete: ${repaired} item(s) fixed.`) : chalk.bold("\nNothing to repair -- platform state was already intact."));
  });

program
  .command("setup")
  .description("Global platform setup, or (run inside a project) project setup")
  .action(() => {
    const platformRoot = getPlatformRoot();
    console.log(chalk.bold(`Security Platform root: ${platformRoot}`));

    for (const dir of ensurePlatformDirectories(platformRoot)) {
      console.log(dir.created ? chalk.green(`[SUCCESS] Created ${dir.dirPath}`) : chalk.gray(`[INFO] ${dir.dirPath} already exists`));
    }
    const runtimeConfig = ensureRuntimeConfig(platformRoot);
    console.log(
      runtimeConfig.created
        ? chalk.green(`[SUCCESS] Wrote ${runtimeConfig.path}`)
        : chalk.gray(`[INFO] ${runtimeConfig.path} already exists`)
    );

    const dockerEnvPath = path.join(platformRoot, "docker", ".env");
    if (!fs.existsSync(dockerEnvPath)) {
      const zapKey = require("crypto").randomBytes(16).toString("hex");
      fs.writeFileSync(
        dockerEnvPath,
        `ZAP_API_KEY=${zapKey}\nZAP_API_PORT=8090\nZAP_VERSION=latest\nMOBSF_PORT=8000\nMOBSF_VERSION=latest\nNUCLEI_VERSION=latest\n`,
        "utf8"
      );
      console.log(chalk.green(`[SUCCESS] Generated ${dockerEnvPath} with a random ZAP_API_KEY.`));
    } else {
      console.log(chalk.gray(`[INFO] ${dockerEnvPath} already exists.`));
    }

    const cwd = process.cwd();
    const isPlatformRoot = path.resolve(cwd).toLowerCase() === path.resolve(platformRoot).toLowerCase();
    if (isPlatformRoot) {
      console.log(chalk.cyan("\nRunning from the platform root -- global setup only; no project to configure here."));
      console.log(chalk.bold("\nGlobal setup complete."));
      console.log(`Run ${chalk.cyan("security doctor")} to verify the full prerequisite/service picture.`);
      return;
    }

    console.log(chalk.bold(`\nDetecting project stack in: ${cwd}`));
    const detected = detectProjectStack(cwd);
    const detectedNames = (Object.keys(detected) as Array<keyof typeof detected>).filter((k) => detected[k]);
    if (detectedNames.length === 0) {
      console.log(chalk.yellow("[WARNING] No supported technologies detected in this directory."));
    } else {
      console.log(chalk.green(`[SUCCESS] Detected: ${detectedNames.join(", ")}`));
    }

    const profiles = new Set<Profile>();
    if (detected.laravel) profiles.add("web");
    if (detected.api || detected.laravel) profiles.add("api");
    if (detected.android) profiles.add("mobile");
    if (detected.windows) profiles.add("windows");
    if (detected.webview) profiles.add("webview");
    if (profiles.size === 0) profiles.add("quick");
    const activeProfiles = Array.from(profiles);

    const projectName = path.basename(cwd);
    const alreadyConfigured = hasProjectConfig(cwd);

    saveProjectConfig(cwd, {
      schemaVersion: 1,
      name: projectName,
      detected,
      profiles: activeProfiles,
      mcp: { registered: false },
    });

    if (loadScope(cwd)) {
      console.log(chalk.gray("[INFO] .security/scope.yaml already exists, leaving it unchanged."));
    } else {
      saveScope(cwd, {
        schemaVersion: 1,
        environment: "staging",
        allowedDomains: [],
        allowedIpRanges: [],
        allowedUrls: [],
        allowedRepositories: [],
        allowedApplications: [],
        allowedMobileArtifacts: [],
        excludedHosts: [],
        excludedPaths: [],
        authenticationProfiles: [],
        rateLimits: { requestsPerSecond: 5 },
        maxScanDurationMinutes: 60,
        destructiveActionsAllowed: false,
      });
      console.log(chalk.green("[SUCCESS] Created .security/scope.yaml -- edit it before scanning; the default scope authorizes nothing."));
    }

    saveProjectProfile(cwd, { schemaVersion: 1, activeProfiles });

    console.log(
      alreadyConfigured
        ? chalk.green(`[SUCCESS] Updated .security/config.yaml for '${projectName}'.`)
        : chalk.green(`[SUCCESS] Created .security/ for '${projectName}'.`)
    );

    const registered = registerProject(platformRoot, { name: projectName, path: cwd, profiles: activeProfiles });
    console.log(chalk.green(`[SUCCESS] Registered with the platform (first registered: ${registered.registeredAt}).`));

    console.log(chalk.bold("\nProject setup complete."));
    console.log(
      `Next: edit ${chalk.cyan(".security/scope.yaml")} to authorize a target, then run ${chalk.cyan(
        "security scan --full"
      )}, or ask your AI agent to run a security assessment.`
    );
  });

