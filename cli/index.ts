program
  .command("scope")
  .description("View, or add an authorized target to, the project's assessment scope")
  .option("--add-url <url>", "Add a URL to allowedUrls")
  .option("--add-domain <domain>", "Add a domain to allowedDomains")
  .option("--add-artifact <path>", "Add a mobile artifact path to allowedMobileArtifacts")
  .action((opts: { addUrl?: string; addDomain?: string; addArtifact?: string }) => {
    const cwd = process.cwd();
    const scope = loadScope(cwd);
    if (!scope) {
      console.log(chalk.yellow("No .security/scope.yaml found here. Run 'security setup' first."));
      process.exitCode = 1;
      return;
    }
    let changed = false;
    if (opts.addUrl && !scope.allowedUrls.includes(opts.addUrl)) {
      scope.allowedUrls.push(opts.addUrl);
      changed = true;
    }
    if (opts.addDomain && !scope.allowedDomains.includes(opts.addDomain)) {
      scope.allowedDomains.push(opts.addDomain);
      changed = true;
    }
    if (opts.addArtifact && !scope.allowedMobileArtifacts.includes(opts.addArtifact)) {
      scope.allowedMobileArtifacts.push(opts.addArtifact);
      changed = true;
    }
    if (changed) {
      saveScope(cwd, scope);
      console.log(chalk.green("[SUCCESS] Scope updated."));
    }
    console.log(JSON.stringify(scope, null, 2));
  });

program
  .command("scan")
  .description("Run a security assessment against the current project's configured scope")
  .option("--full", "Run all applicable tools (default)")
  .option("--web", "Web-focused (informational; tool selection is still driven by detected stack + scope)")
  .option("--api", "API-focused (informational; see --web)")
  .option("--mobile", "Mobile-focused (informational; see --web)")
  .option("--windows", "Windows-focused (no automated Windows scanner yet -- see windows-security skill)")
  .option("--webview", "WebView-focused (covered via the android/windows adapters + webview-security skill)")
  .action(async (opts: Record<string, boolean>) => {
    const cwd = process.cwd();
    const platformRoot = getPlatformRoot();
    const flags = Object.keys(opts).filter((k) => opts[k]);
    if (flags.length > 0 && !flags.includes("full")) {
      console.log(chalk.gray(`[INFO] --${flags.join(", --")} noted, but per-profile filtering isn't implemented yet -- running every tool applicable to the detected stack and configured scope.`));
    }
    console.log(chalk.bold(`Running security assessment for: ${cwd}`));
    try {
      const result = await runAssessment({ platformRoot, projectPath: cwd });
      logLine(platformRoot, `assessment ${result.assessmentId} project=${cwd} findings=${result.findings.length} tools=${result.toolsRun.join(",")}`);

      console.log(chalk.bold(`\nTools run: ${result.toolsRun.join(", ") || "(none)"}`));
      if (result.toolsSkipped.length > 0) {
        console.log(chalk.yellow("Tools skipped:"));
        for (const s of result.toolsSkipped) console.log(chalk.yellow(`  - ${s.name}: ${s.reason}`));
      }
      if (result.errors.length > 0) {
        console.log(chalk.red("Errors:"));
        for (const e of result.errors) console.log(chalk.red(`  - ${e.tool} against ${e.target}: ${e.message}`));
      }
      console.log(chalk.bold(`\nFindings: ${result.findings.length}`));
      console.log(`Report: ${result.reportDir}`);
    } catch (err) {
      console.log(chalk.red(`[ERROR] ${(err as Error).message}`));
      process.exitCode = 1;
    }
  });

