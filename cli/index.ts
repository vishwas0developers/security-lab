program
  .command("clean")
  .description("Remove generated reports/evidence older than the retention period")
  .option("--days <n>", "Retention period in days", "30")
  .action((opts: { days: string }) => {
    const platformRoot = getPlatformRoot();
    const cutoff = Date.now() - parseInt(opts.days, 10) * 24 * 60 * 60 * 1000;
    let removed = 0;
    for (const sub of ["reports", "evidence"]) {
      const dir = path.join(platformRoot, sub);
      if (!fs.existsSync(dir)) continue;
      for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const entryPath = path.join(dir, entry.name);
        const stat = fs.statSync(entryPath);
        if (stat.mtimeMs < cutoff) {
          fs.rmSync(entryPath, { recursive: true, force: true });
          console.log(chalk.green(`[SUCCESS] Removed ${entryPath}`));
          removed++;
        }
      }
    }
    console.log(chalk.bold(`Clean complete: ${removed} item(s) removed (older than ${opts.days} days).`));
  });

