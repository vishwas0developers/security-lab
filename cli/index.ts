program
  .command("install")
  .argument("<agent>", `AI agent to configure (${SUPPORTED_AGENTS.join(", ")})`)
  .description("Configure MCP + deploy Security Skills for an AI agent in the current project")
  .action((agent: string) => {
    if (!(SUPPORTED_AGENTS as readonly string[]).includes(agent)) {
      console.log(chalk.red(`Unknown agent '${agent}'.`));
      console.log(`Supported agents: ${SUPPORTED_AGENTS.join(", ")}`);
      process.exitCode = 1;
      return;
    }
    const platformRoot = getPlatformRoot();
    const info = describeAgent(agent as AgentId);
    console.log(chalk.bold(`Installing ${info.label} integration in: ${process.cwd()}`));
    if (info.mcpConfig && !info.mcpVerified) {
      console.log(chalk.yellow(`[WARNING] MCP config path for '${agent}' is an unverified generic fallback (${info.mcpConfig}). Confirm against ${info.label}'s current docs if it doesn't take effect.`));
    }
    installAgent(agent, platformRoot, process.cwd());
    console.log(chalk.bold("\nAgent integration complete."));
  });

program
  .command("doctor")
  .description("Validate prerequisites (Node, Docker, WSL2, tool health)")
  .action(() => {
    console.log(chalk.bold("Security Platform Doctor\n"));

    let hasError = false;
    let hasWarning = false;
    for (const result of runAllChecks()) {
      console.log(`${statusTag(result.status)} ${result.name}: ${result.message}`);
      if (result.remediation) {
        console.log(chalk.gray(`           ${result.remediation}`));
      }
      if (result.status === "error") hasError = true;
      if (result.status === "warning") hasWarning = true;
    }

    const platformRoot = getPlatformRoot();
    console.log(chalk.bold(`\nPlatform root: ${platformRoot}`));
    const missingDirs = RUNTIME_DIRS.filter((d) => !fs.existsSync(path.join(platformRoot, d)));
    if (missingDirs.length > 0) {
      console.log(`${statusTag("warning")} Missing directories: ${missingDirs.join(", ")} -- run 'security setup' to create them.`);
      hasWarning = true;
    } else {
      console.log(`${statusTag("ok")} All platform directories present.`);
    }
    const configPath = getRuntimeConfigPath(platformRoot);
    if (fs.existsSync(configPath)) {
      console.log(`${statusTag("ok")} Runtime config present (${configPath}).`);
    } else {
      console.log(`${statusTag("warning")} Runtime config missing -- run 'security setup'.`);
      hasWarning = true;
    }

    console.log("");
    if (hasError) {
      console.log(chalk.red("Doctor found errors that must be fixed."));
      process.exitCode = 1;
    } else if (hasWarning) {
      console.log(chalk.yellow("Doctor found warnings. The CLI works, but some functionality is limited until they're resolved."));
    } else {
      console.log(chalk.green("Everything looks good."));
    }
  });

