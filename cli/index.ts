program
  .command("validate")
  .argument("<findingId>", "Finding id from the most recent report")
  .description("Show a finding's detail, optionally updating its status/confidence after manual validation")
  .option("--status <status>", "New status: suspected|probable|confirmed|false_positive|unable_to_validate")
  .option("--note <note>", "Validation note, recorded as an evidence entry")
  .action((findingId: string, opts: { status?: string; note?: string }) => {
    const platformRoot = getPlatformRoot();
    const dir = latestReportDir(platformRoot);
    if (!dir) {
      console.log(chalk.yellow("No reports found."));
      return;
    }
    const findingsPath = path.join(dir, "findings.json");
    const data = JSON.parse(fs.readFileSync(findingsPath, "utf8")) as { meta: unknown; findings: Finding[] };
    const finding = data.findings.find((f) => f.id === findingId);
    if (!finding) {
      console.log(chalk.red(`No finding with id '${findingId}' in the latest report.`));
      process.exitCode = 1;
      return;
    }
    if (opts.status) {
      finding.status = opts.status as Finding["status"];
      finding.validated_by = Array.from(new Set([...finding.validated_by, "manual"]));
      if (opts.note) finding.evidence.push(`[validation note] ${opts.note}`);
      fs.writeFileSync(findingsPath, JSON.stringify(data, null, 2), "utf8");
      console.log(chalk.green(`[SUCCESS] Updated ${findingId} -> status=${finding.status}`));
    }
    console.log(JSON.stringify(finding, null, 2));
  });

