function notImplemented(command: string): void {
  console.log(chalk.yellow(`'security ${command}' is not implemented yet.`));
}

function statusTag(status: CheckStatus): string {
  switch (status) {
    case "ok":
      return chalk.green("[OK]     ");
    case "warning":
      return chalk.yellow("[WARNING]");
    case "error":
      return chalk.red("[ERROR]  ");
    default:
      return chalk.gray("[SKIPPED]");
  }
}

function logLine(platformRoot: string, message: string): void {
  const logsDir = path.join(platformRoot, "logs");
  fs.mkdirSync(logsDir, { recursive: true });
  const line = `${new Date().toISOString()} ${message}\n`;
  fs.appendFileSync(path.join(logsDir, "assessments.log"), line, "utf8");
}

function latestReportDir(platformRoot: string): string | null {
  const reportsDir = path.join(platformRoot, "reports");
  if (!fs.existsSync(reportsDir)) return null;
  // Sort by mtime, not name: report dirs are named
  // "assessment-YYYY-MM-DD-<random-id>", and the random id suffix means two
  // reports from the same day do NOT sort chronologically by name (e.g.
  // "...-0728e94f" can sort before "...-a7ef94a6" even though it was
  // generated later).
  const dirs = fs
    .readdirSync(reportsDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => ({ name: d.name, mtimeMs: fs.statSync(path.join(reportsDir, d.name)).mtimeMs }))
    .sort((a, b) => a.mtimeMs - b.mtimeMs);
  return dirs.length > 0 ? path.join(reportsDir, dirs[dirs.length - 1].name) : null;
}

